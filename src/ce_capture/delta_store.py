"""The record store on Databricks: three Delta tables behind a SQL warehouse (D17).

One table per kind of record. Each row holds the whole record as JSON text in
`record`, returned as written, with a few columns copied out of it for
lookups and analysis, and `links`: the IDs the record points to, so "what
points to this record" is one query.

A record is written once: the insert is a `MERGE` that does nothing when the
ID exists, and an insert of zero rows is `RecordExists`. Two writers of one ID
at the same moment are left to Delta's conflict check; IDs are generated by
the server, so this does not arise in practice.

Records never change, so a record read or written once is kept in memory and
not read again.
"""

from __future__ import annotations

import json
import os
import re
import threading
from collections import OrderedDict
from collections.abc import Mapping
from typing import Protocol

from ce_capture import workspace
from ce_capture.config import CaptureSettings
from ce_capture.storage import (
    ID_FIELD,
    KINDS,
    TIME_FIELD,
    Kind,
    RecordExists,
    _links,
    check_id,
    newest_first,
    oldest_first,
)
from ce_capture.warehouse import Result, SqlWarehouse, StoreError

IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_]{0,99}")
PREFIX = re.compile(r"[A-Za-z_][A-Za-z0-9_]{0,39}|")
TABLE = {
    "request": "request_records",
    "resolved": "resolved_records",
    "outcome": "outcome_records",
}
CACHE_SIZE = 2048

# Column: (SQL type, where the value sits in the record). The record's own ID
# and time, `links` and `record` are added for every table.
COLUMNS: dict[Kind, dict[str, tuple[str, tuple[str, ...]]]] = {
    "request": {
        "session_id": ("STRING", ("source", "session_id")),
        "status": ("STRING", ("capture", "status")),
        "turn": ("INT", ("source", "turn")),
    },
    "resolved": {"request_id": ("STRING", ("request_id",))},
    "outcome": {
        "request_id": ("STRING", ("request_id",)),
        "resolved_id": ("STRING", ("resolved_id",)),
        "verdict": ("STRING", ("verdict",)),
        "mode": ("STRING", ("mode",)),
        "rules_version": ("STRING", ("rules_version",)),
    },
}


class Executor(Protocol):
    def execute(
        self, statement: str, parameters: Mapping[str, str | None] | None = None
    ) -> Result: ...


def _at(record: dict, path: tuple[str, ...]) -> str | None:
    value: object = record
    for name in path:
        value = value.get(name) if isinstance(value, dict) else None
    if value is None or isinstance(value, dict | list):
        return None
    return str(value)


def _cast(name: str, sql_type: str) -> str:
    return f":{name}" if sql_type == "STRING" else f"try_cast(:{name} AS {sql_type})"


class DeltaRecordStore:
    """Request, resolved and outcome records in Delta tables."""

    def __init__(
        self, warehouse: Executor, catalog: str, schema: str, prefix: str = "ce_mcp_"
    ) -> None:
        for what, value in (("catalog", catalog), ("schema", schema)):
            if not value or not IDENTIFIER.fullmatch(value):
                raise StoreError(
                    f"The record store needs a plain {what} name "
                    f"(CE_CAPTURE_STORE_{what.upper()})."
                )
        if not PREFIX.fullmatch(prefix):
            raise StoreError("The record table prefix is not a plain name.")
        self.warehouse = warehouse
        self.catalog, self.schema, self.prefix = catalog, schema, prefix
        self._cache: OrderedDict[tuple[Kind, str], str] = OrderedDict()
        self._lock = threading.Lock()

    @classmethod
    def from_settings(cls, settings: CaptureSettings) -> DeltaRecordStore:
        import httpx

        warehouse_id = settings.warehouse_id or os.getenv("DATABRICKS_WAREHOUSE_ID")
        if not warehouse_id:
            raise StoreError(
                "The Delta record store needs a SQL warehouse: set "
                "CE_CAPTURE_WAREHOUSE_ID."
            )
        host = workspace.workspace_host(
            settings.databricks_host or os.getenv("DATABRICKS_HOST"), StoreError
        )
        client = httpx.Client(timeout=65, follow_redirects=False, trust_env=False)
        token = workspace.token_source(
            host, settings.databricks_profile, client, StoreError
        )
        warehouse = SqlWarehouse(
            host, warehouse_id, token, client, timeout=settings.store_timeout
        )
        return cls(
            warehouse,
            settings.store_catalog or "",
            settings.store_schema or "",
            settings.store_prefix,
        )

    # ── names and statements ─────────────────────────────────────────────────

    def table(self, kind: Kind) -> str:
        return f"`{self.catalog}`.`{self.schema}`.`{self.prefix}{TABLE[kind]}`"

    def ddl(self) -> list[str]:
        """The statements that create the three tables, if they are not there."""
        out = []
        for kind in KINDS:
            columns = [f"{ID_FIELD[kind]} STRING NOT NULL"]
            columns += [f"{name} {t}" for name, (t, _) in COLUMNS[kind].items()]
            columns += [
                f"{TIME_FIELD[kind]} TIMESTAMP",
                "links ARRAY<STRING>",
                "record STRING NOT NULL",
            ]
            body = ",\n  ".join(columns)
            out.append(f"CREATE TABLE IF NOT EXISTS {self.table(kind)} (\n  {body}\n)")
        return out

    def grants(self, principal: str) -> list[str]:
        """What a reader and writer of the tables needs, such as an app's
        service principal (named by its application ID)."""
        if not re.fullmatch(r"[A-Za-z0-9_.@ -]{1,128}", principal):
            raise StoreError("Not a principal name.")
        who = f"`{principal}`"
        out = [
            f"GRANT USE CATALOG ON CATALOG `{self.catalog}` TO {who}",
            f"GRANT USE SCHEMA ON SCHEMA `{self.catalog}`.`{self.schema}` TO {who}",
        ]
        out += [
            f"GRANT SELECT, MODIFY ON TABLE {self.table(kind)} TO {who}"
            for kind in KINDS
        ]
        return out

    # ── the cache ────────────────────────────────────────────────────────────

    def _keep(self, kind: Kind, record_id: str, text: str) -> None:
        with self._lock:
            self._cache[(kind, record_id)] = text
            self._cache.move_to_end((kind, record_id))
            while len(self._cache) > CACHE_SIZE:
                self._cache.popitem(last=False)

    def _load(self, kind: Kind, text: str | None) -> dict:
        try:
            record = json.loads(text or "")
        except ValueError:
            raise StoreError(f"A stored {kind} record is not JSON.") from None
        if not isinstance(record, dict):
            raise StoreError(f"A stored {kind} record is not JSON.")
        record_id = record.get(ID_FIELD[kind])
        if isinstance(record_id, str):
            self._keep(kind, record_id, text or "")
        return record

    # ── the four operations ──────────────────────────────────────────────────

    def write(self, kind: Kind, record: dict) -> str:
        record_id = check_id(record[ID_FIELD[kind]])
        text = json.dumps(record, ensure_ascii=False)
        key, time = ID_FIELD[kind], TIME_FIELD[kind]
        extra = COLUMNS[kind]
        names = [key, *extra, time, "links", "record"]
        values = [
            "s.id",
            *(_cast(name, t) for name, (t, _) in extra.items()),
            "try_cast(:at AS TIMESTAMP)",
            "from_json(:links, 'array<string>')",
            ":record",
        ]
        parameters = {"id": record_id}
        parameters |= {name: _at(record, path) for name, (_, path) in extra.items()}
        parameters |= {
            "at": _at(record, (time,)),
            "links": json.dumps(sorted(_links(kind, record))),
            "record": text,
        }
        result = self.warehouse.execute(
            f"MERGE INTO {self.table(kind)} AS t USING (SELECT :id AS id) AS s "
            f"ON t.{key} = s.id WHEN NOT MATCHED THEN "
            f"INSERT ({', '.join(names)}) VALUES ({', '.join(values)})",
            parameters,
        )
        if _inserted(result) == 0:
            raise RecordExists(f"{kind} record {record_id} exists already")
        self._keep(kind, record_id, text)
        return record_id

    def read(self, kind: Kind, record_id: str) -> dict | None:
        try:
            check_id(record_id)
        except ValueError:
            return None
        with self._lock:
            text = self._cache.get((kind, record_id))
        if text is not None:
            return json.loads(text)
        result = self.warehouse.execute(
            f"SELECT record FROM {self.table(kind)} "
            f"WHERE {ID_FIELD[kind]} = :id LIMIT 1",
            {"id": record_id},
        )
        return self._load(kind, result.rows[0][0]) if result.rows else None

    def by_session(self, session_id: str, kind: Kind = "request") -> list[dict]:
        """A session's records, oldest first."""
        if "session_id" not in COLUMNS[kind]:
            return []  # only a request record carries its session
        result = self.warehouse.execute(
            f"SELECT record FROM {self.table(kind)} WHERE session_id = :session",
            {"session": session_id},
        )
        return oldest_first(kind, [self._load(kind, row[0]) for row in result.rows])

    def pointing_to(self, record_id: str) -> list[tuple[Kind, dict]]:
        """Every record that names `record_id`, newest first."""
        result = self.warehouse.execute(
            " UNION ALL ".join(
                f"SELECT '{kind}' AS kind, record FROM {self.table(kind)} "
                "WHERE array_contains(links, :id)"
                for kind in KINDS
            ),
            {"id": record_id},
        )
        found = []
        for kind, text in result.rows:
            if kind not in KINDS:
                raise StoreError("The record store answered in an unknown form.")
            found.append((kind, self._load(kind, text)))
        return newest_first(found)

    def resolved_for(self, request_id: str) -> list[dict]:
        """A request's resolved records, newest first."""
        result = self.warehouse.execute(
            f"SELECT record FROM {self.table('resolved')} WHERE request_id = :id",
            {"id": request_id},
        )
        rows = [("resolved", self._load("resolved", row[0])) for row in result.rows]
        return [r for _, r in newest_first(rows)]


def _inserted(result: Result) -> int:
    """How many rows a MERGE inserted, from its one row of counts."""
    rows = result.dicts()
    value = rows[0].get("num_inserted_rows") if rows else None
    try:
        return int(value)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        raise StoreError("The record store did not say whether it wrote.") from None
