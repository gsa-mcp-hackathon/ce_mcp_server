"""Build a table sidecar from scratch and write it.

Inputs: the stored table and `source_columns`, the BLS dictionary, the master
sidecar (row meaning, weight, its own id and version), the row key, and the
table's overrides file if there is one. No earlier sidecar is read.
"""

from collections import Counter
from pathlib import Path

import duckdb
import yaml

from ce_ingest.models import Survey
from ce_ingest.registry import SOURCE_COLUMNS_TABLE
from ce_ingest.writers.base import Writer
from ce_meta.sidecars import custom_properties
from ce_sidecars.dictionary import FileDictionary
from ce_sidecars.generate import Review, StoredColumn, build_properties

HEADER = """\
# Table sidecar for the CE Interview Survey {table} table, written against the
# Open Data Contract Standard (ODCS) v3.2.0.
#
# Status: draft, version {version}. GENERATED by `ce-sidecars generate` from the
# BLS data dictionary ({release} release), the loader's stored table and
# source_columns, the master sidecar, and overrides/{table_id}.yaml. Do not
# edit it by hand: change the overrides file and generate it again.
# Not yet validated against the ODCS JSON Schema.
#
# Columns that still need a person's decision are tagged needs-review, with a
# review:<reason> tag for each reason, and listed in {table_id}.review.md.
# Survey facts are in the master sidecar (ce:master);
# the meaning of each "ce:" property is in vocabulary.yaml.

"""

# The level of a table's rows: the default ce:level the pattern rules give its
# columns. Every table but the member table describes a consumer unit.
ROW_LEVELS = {"member_interview": "member"}

ROW_SENTENCES = {
    "consumer_unit_interview": "One row per consumer unit per quarterly interview.",
    "member_interview": (
        "One row per member of a consumer unit per quarterly interview."
    ),
    "expenditure_item_month": (
        "One row per expenditure item (UCC) per reference month."
    ),
    "income_item_month": "One row per income item (UCC) per reference month.",
    "imputed_income_item_month": (
        "One row per imputed version of an income item per reference month."
    ),
    "expn_record": "One row per record reported in one questionnaire section.",
    "tax_unit": "One row per tax unit within a consumer unit.",
}

# The detailed expenditure (EXPN) tables share a structure, so they share a
# template: a default row key, and table text built from the dictionary's
# section description. The dictionary names a file by its code (RNT); the loader
# stores it as expn_<code>.
EXPN_PREFIX = "expn_"
EXPN_ROW = "expn_record"
DEFAULT_ROW_KEYS = {EXPN_ROW: ["newid", "seqno", "alcno"]}


def dictionary_file(table: str) -> str:
    """The dictionary's name for a stored table: `expn_rnt` is its file `RNT`."""
    return table.removeprefix(EXPN_PREFIX)


def expn_template(table: str, dictionary: FileDictionary) -> dict:
    """Table text for a detailed expenditure table, from its dictionary section."""
    sections = Counter(v.section for v in dictionary.variables.values() if v.section)
    section = " ".join(sections.most_common(1)[0][0].split()) if sections else None
    about = (
        f'questionnaire section "{section}"' if section else "one questionnaire section"
    )
    return {
        "description": {
            "purpose": (
                f"Detailed expenditure records from the Interview {about} "
                f"(BLS file {dictionary.file}), as loaded.\n"
            ),
            "limitations": (
                "A consumer unit has rows only when the section applied to it, and "
                "may have several. BLS releases the file for five quarters at once; "
                "it is stored by interview quarter (qyear). See the master sidecar "
                "for the survey design.\n"
            ),
            "usage": (
                "Detail behind the consumer unit's expenditures. The table carries "
                "no weight: sum its rows to newid, then use the weight of the fmli "
                "row with the same newid.\n"
            ),
        },
        "schema": {
            "businessName": (
                f"CE Interview detailed expenditures: {section}"
                if section
                else f"CE Interview detailed expenditures ({dictionary.file})"
            ),
            "description": ROW_SENTENCES[EXPN_ROW],
            "tags": ["survey", "detailed-expenditure"],
        },
    }


AUTHORITATIVE = [
    {
        "type": "businessDefinition",
        "url": "https://www.bls.gov/cex/pumd-getting-started-guide.htm",
        "description": "BLS public-use microdata getting started guide.",
    },
    {
        "type": "glossary",
        "url": "vocabulary.yaml#properties",
        "description": (
            "Definitions of the ce: custom properties used in this contract."
        ),
    },
]

INSTRUCTIONS = (
    "This contract describes one table of the CE Interview Survey. Read the "
    "master sidecar named in ce:master for the survey design and for how this "
    "table relates to the others, and the vocabulary it names for the meaning "
    "of each ce: property.\n"
)
MASTER_CONSTRAINT = {
    "id": "c-master-required",
    "constraint": (
        "Do not interpret this table without the master sidecar; the survey "
        "design is not described here.\n"
    ),
    "tags": ["master-sidecar"],
}


def stored_columns(writer: Writer, survey: Survey, table: str) -> list[StoredColumn]:
    """The stored table's columns in order, with their BLS spelling."""
    source = writer.duckdb_from(survey, table)
    if source is None:
        raise ValueError(f"{survey}/{table}: no stored partitions")
    described = duckdb.connect().execute(f"describe select * from {source}").fetchall()
    rows = writer.read_rows(SOURCE_COLUMNS_TABLE)
    original: dict[str, str] = {}
    if rows is not None:
        for r in rows.to_pylist():
            if r["survey"] == survey and r["table"] == table:
                original.setdefault(r["name"], r["original_name"])
    return [
        StoredColumn(name, db_type, original.get(name))
        for name, db_type, *_ in described
    ]


def _quote(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def observed_values(
    writer: Writer, survey: Survey, table: str, columns: list[str], limit: int = 50
) -> dict[str, set[str]]:
    """Distinct non-null values of a few columns, as text."""
    source = writer.duckdb_from(survey, table)
    con = duckdb.connect()
    out: dict[str, set[str]] = {}
    for c in columns:
        q = _quote(c)
        rows = con.execute(
            f"select distinct {q}::varchar from {source} "
            f"where {q} is not null limit {limit}"
        ).fetchall()
        out[c] = {r[0] for r in rows}
    return out


def check_row_key(writer: Writer, survey: Survey, table: str, key: list[str]) -> None:
    """Stop unless the key's columns identify every stored row."""
    source = writer.duckdb_from(survey, table)
    cols = ", ".join(_quote(c) for c in key)
    n, distinct = (
        duckdb.connect()
        .execute(f"select count(*), count(distinct ({cols})) from {source}")
        .fetchone()
    )
    if n != distinct:
        raise ValueError(
            f"{survey}/{table}: row key {key} is not unique "
            f"({n} rows, {distinct} distinct keys)"
        )


def _schema_object(
    table: str, row_represents: str, key: list[str], text: dict, props: list[dict]
) -> dict:
    schema: dict = {
        "name": table,
        "id": table,
        "physicalName": table,
        "physicalType": "table",
        "businessName": text.get("businessName", f"CE Interview {table} table"),
        "description": text.get("description", ROW_SENTENCES.get(row_represents, "")),
    }
    if "tags" in text:
        schema["tags"] = text["tags"]
    schema["customProperties"] = [
        {"property": "ce:rowRepresents", "value": row_represents},
        {"property": "ce:rowKey", "value": key},
    ]
    unique = (
        f"{key[0]} is unique across the stored table."
        if len(key) == 1
        else f"The row key ({', '.join(key)}) is unique across the stored table."
    )
    schema["quality"] = [
        {
            "metric": "duplicateValues",
            "mustBe": 0,
            "description": unique,
            "dimension": "uniqueness",
            "type": "library",
            "severity": "error",
        }
    ]
    schema["properties"] = props
    return schema


def generate_table_sidecar(
    writer: Writer,
    survey: Survey,
    table: str,
    dictionary: FileDictionary,
    master: dict,
    overrides: dict | None,
    version: str,
    row_key: list[str] | None = None,
) -> tuple[dict, Review]:
    """A complete table sidecar, built from scratch, and its review list."""
    overrides = overrides or {}
    table_id = f"ce-interview-{table}"
    facts = custom_properties(master)
    entry = next(
        (t for t in facts.get("ce:tables", []) if t["sidecar"] == table_id), None
    )
    if entry is None:
        raise ValueError(f"{table_id} is not in the master sidecar's ce:tables")
    template = (
        expn_template(table, dictionary) if entry["rowRepresents"] == EXPN_ROW else {}
    )
    key = (
        row_key
        or overrides.get("rowKey")
        or DEFAULT_ROW_KEYS.get(entry["rowRepresents"])
    )
    if not key:
        raise ValueError(f"{table_id}: no row key (--row-key or the overrides file)")

    columns = stored_columns(writer, survey, table)
    if not set(key) <= {c.name for c in columns}:
        raise ValueError(f"{table_id}: row key {key} names missing columns")
    check_row_key(writer, survey, table, key)

    weight = facts.get("ce:weight", {})
    weight_column = weight.get("column") if weight.get("table") == table_id else None
    flags = set(dictionary.flag_of())
    for name, override in (overrides.get("columns") or {}).items():
        if "ce:flagFor" in override.get("customProperties", {}):
            flags.add(name)  # a flag the dictionary doesn't link
    probe = [c.name for c in columns if c.name in flags or c.name in dictionary.codes]
    observed = observed_values(writer, survey, table, probe)
    props, review = build_properties(
        columns,
        dictionary,
        overrides.get("columns"),
        observed,
        key,
        weight_column,
        ROW_LEVELS.get(entry["rowRepresents"], "consumer_unit"),
    )

    description = overrides.get("description") or template.get("description")
    if description is None:
        description = {
            "purpose": (
                f"The {dictionary.file} table of the BLS Consumer Expenditure "
                "Interview Survey public-use microdata, as loaded.\n"
            ),
            "limitations": "See the master sidecar for the survey design.\n",
        }
        review.add("Table description not written yet", "(table)")
    context: dict = {"instructions": INSTRUCTIONS}
    if overrides.get("verifiedStatements"):
        context["verifiedStatements"] = overrides["verifiedStatements"]
    context["constraints"] = [MASTER_CONSTRAINT]
    if entry.get("version") != version:
        review.add(
            f"Master lists {table_id} at version {entry.get('version')}, not {version}",
            "(table)",
        )

    doc = {
        "apiVersion": "v3.2.0",
        "kind": "DataContract",
        "id": table_id,
        "name": table_id.replace("-", "_"),
        "version": version,
        "status": "draft",
        "domain": "consumer-expenditure",
        "dataProduct": "ce-interview-survey",
        "tenant": "TBD",
        "description": description,
        "authoritativeDefinitions": AUTHORITATIVE,
        "context": context,
        "customProperties": [
            {
                "property": "ce:master",
                "value": {"id": master["id"], "version": master["version"]},
            }
        ],
        "schema": [
            _schema_object(
                table,
                entry["rowRepresents"],
                key,
                overrides.get("schema") or template.get("schema", {}),
                props,
            )
        ],
        "tags": ["bls", "consumer-expenditure", "survey"],
    }
    return doc, review


def dump_sidecar(doc: dict, table: str, release: int) -> str:
    body = yaml.safe_dump(doc, sort_keys=False, width=88, allow_unicode=True)
    return (
        HEADER.format(
            table=table, version=doc["version"], release=release, table_id=doc["id"]
        )
        + body
    )


def load_yaml(path: Path) -> dict | None:
    return yaml.safe_load(path.read_text()) if path.exists() else None
